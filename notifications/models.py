"""Models for in-app notifications."""
from django.conf import settings
from django.db import models


class Notification(models.Model):
    """A message shown to one user (bell icon and notifications page)."""

    class Category(models.TextChoices):
        COMPLAINT = "complaint", "Complaint"
        TASK = "task", "Task"
        SYSTEM = "system", "System"

    recipient = models.ForeignKey(
        settings.AUTH_USER_MODEL, on_delete=models.CASCADE, related_name="notifications"
    )
    title = models.CharField(max_length=150)
    message = models.TextField(blank=True)
    category = models.CharField(max_length=20, choices=Category.choices, default=Category.SYSTEM)
    # Internal path only (for example /complaints/5/), always generated by the server.
    link = models.CharField(max_length=255, blank=True)
    is_read = models.BooleanField(default=False)
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        ordering = ["-created_at", "-id"]
        indexes = [models.Index(fields=["recipient", "is_read"])]

    def __str__(self):
        return f"{self.title} -> {self.recipient}"